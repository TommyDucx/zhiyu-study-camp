import { readFile, writeFile, mkdir, cp } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SCRIPT_ORDER = ['data.js', 'engine.js', 'storage.js', 'app.js'];

async function read(relativePath) {
  return readFile(join(root, relativePath), 'utf8');
}

function assertInlineable(html) {
  const external = html.match(/(?:src|href)=["'](?!#|data:|\.\/)[^"']+["']/g);
  if (external) {
    throw new Error(`Dist build cannot contain external asset references:\n${external.join('\n')}`);
  }
}

async function main() {
  let html = await read('index.html');
  const css = await read('assets/styles.css');
  const scripts = await Promise.all(SCRIPT_ORDER.map((file) => read(`src/${file}`)));

  for (const [index, source] of scripts.entries()) {
    try {
      new Function(source);
    } catch (error) {
      throw new Error(`Syntax error in src/${SCRIPT_ORDER[index]}: ${error.message}`);
    }
  }

  if (!html.includes('<link rel="stylesheet" href="./assets/styles.css">')) {
    throw new Error('index.html must link ./assets/styles.css in the expected place.');
  }
  html = html.replace(
    '<link rel="stylesheet" href="./assets/styles.css">',
    () => `<style>\n${css.trim()}\n</style>`,
  );

  for (const [index, source] of scripts.entries()) {
    const tag = `<script src="./src/${SCRIPT_ORDER[index]}"></script>`;
    if (!html.includes(tag)) throw new Error(`Missing script tag: ${tag}`);
    html = html.replace(tag, () => `<script>\n${source.trim()}\n</script>`);
  }

  html = html.replace(
    '<!DOCTYPE html>',
    `<!DOCTYPE html>\n<!-- Generated by scripts/build.mjs. Edit source files instead. -->`,
  );
  assertInlineable(html);

  const embeddedScripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((match) => match[1]);
  if (embeddedScripts.length !== SCRIPT_ORDER.length) {
    throw new Error(`Expected ${SCRIPT_ORDER.length} embedded scripts, found ${embeddedScripts.length}.`);
  }
  embeddedScripts.forEach((source, index) => {
    try {
      new Function(source);
    } catch (error) {
      throw new Error(`Generated bundle is invalid after inlining (${SCRIPT_ORDER[index]}): ${error.message}`);
    }
  });

  await mkdir(join(root, 'dist'), { recursive: true });
  await writeFile(join(root, 'dist/index.html'), html, 'utf8');
  await writeFile(join(root, 'dist/.nojekyll'), '', 'utf8');
  await cp(join(root, 'docs'), join(root, 'dist/docs'), { recursive: true });
  for (const file of ['README.md', 'GLOSSARY.md', 'LICENSE']) {
    await cp(join(root, file), join(root, 'dist', file));
  }

  const kb = (Buffer.byteLength(html) / 1024).toFixed(1);
  console.log(`Built dist/index.html (${kb} KB, fully self-contained).`);
  console.log('Copied architecture docs to dist/docs for GitHub Pages.');
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
